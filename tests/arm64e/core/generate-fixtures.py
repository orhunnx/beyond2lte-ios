#!/usr/bin/env python3
"""Generate actual instruction words with LLVM, never hand-enter opcode fixtures."""
import pathlib,re,subprocess,os
p=pathlib.Path(__file__).resolve().parent
items=[]
for stem in ['pacia','pacib','pacda','pacdb','autia','autib','autda','autdb']:
 for suffix,args in [('reg','x0,x1'),('sp','x30,sp'),('zr','xzr,sp')]:items.append((stem+'_'+suffix,stem+' '+args,'IDENTITY'))
for stem in ['paciza','pacizb','pacdza','pacdzb','autiza','autizb','autdza','autdzb','xpaci','xpacd']:
 for suffix,args in [('reg','x0'),('zr','xzr')]:items.append((stem+'_'+suffix,stem+' '+args,'IDENTITY'))
for stem in ['pacia1716','pacib1716','autia1716','autib1716','paciasp','pacibsp','autiasp','autibsp','paciaz','pacibz','autiaz','autibz','xpaclri']:items.append((stem,stem,'IDENTITY'))
for stem in ['braa','brab','blraa','blrab']:
 for suffix,args in [('normal','x0,x1'),('lr','x30,x30'),('sp','x0,sp'),('zr','xzr,sp')]:items.append((stem+'_'+suffix,stem+' '+args,'BRANCH'))
for stem in ['braaz','brabz','blraaz','blrabz']:
 for suffix,args in [('normal','x0'),('lr','x30'),('zr','xzr')]:items.append((stem+'_'+suffix,stem+' '+args,'BRANCH'))
for stem in ['retaa','retab']:items.append((stem,stem,'BRANCH'))
for stem in ['ldraa','ldrab']:
 for suffix,args in [('zero','x0,[x1]'),('plus','x0,[x1,#4088]'),('minus','x0,[x1,#-4096]'),('wbplus','x0,[x1,#8]!'),('wbminus','x0,[x1,#-8]!'),('sp','x0,[sp,#8]!'),('zr','xzr,[sp,#8]!'),('overlap','x1,[x1]')]:items.append((stem+'_'+suffix,stem+' '+args,'MEMORY'))
for key,asm in [('ldapr_x','ldapr x0,[x1]'),('ldapr_w','ldapr w0,[x1]'),('ldaprb','ldaprb w0,[x1]'),('ldaprh','ldaprh w0,[x1]'),('ldapr_sp','ldapr x0,[sp]'),('ldapr_zr','ldapr xzr,[x1]'),('ldaprb_zr','ldaprb wzr,[sp]')]:items.append((key,asm,'MEMORY'))
for key,args in [('pacga','x0,x1,x2'),('pacga_alias_n','x1,x1,x2'),('pacga_alias_m','x2,x1,x2'),('pacga_zr_n','x0,xzr,sp'),('pacga_zr_d','xzr,x1,sp')]:items.append((key,'pacga '+args,'GENERIC'))
r=subprocess.run([os.getenv('LLVM_MC','/opt/homebrew/opt/llvm/bin/llvm-mc'),'-triple=aarch64','-mattr=+pauth,+rcpc','-show-encoding'],input='\n'.join(x[1] for x in items),capture_output=True,text=True,check=True)
words=[]
for line in r.stdout.splitlines():
 m=re.search(r'encoding: \[([^]]+)\]',line)
 if m:words.append(int.from_bytes(bytes(int(v.strip(),16) for v in m[1].split(',')),'little'))
assert len(words)==len(items)
lines=['/* Generated by LLVM MC from fixtures.S; do not edit numeric words. */','enum fixture_kind { IDENTITY, BRANCH, MEMORY, GENERIC };','struct fixture { const char *name; uint32_t word; enum fixture_kind kind; };','static const struct fixture fixtures[] = {']
for (name,asm,kind),word in zip(items,words):lines.append(f'    {{"{name}", UINT32_C(0x{word:08x}), {kind}}}, /* {asm} */')
lines+=['};']
(p/'fixtures.h').write_text('\n'.join(lines)+'\n');(p/'fixtures.S').write_text('.text\n'+ '\n'.join(x[1] for x in items)+'\n')
print(f'Generated {len(words)} LLVM instruction fixtures')
